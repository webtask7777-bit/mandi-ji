export const CROP_TOPICS = Object.freeze(TOPIC_ROWS.map(([id, nameHi, nameEn, category, commodityIds]) => Object.freeze({
  id, nameHi, nameEn, category,
  commodityIds: Object.freeze(commodityIds.split(' ')),
})));

const normalizeId = value => typeof value === 'string' ? value.trim().toLowerCase() : '';
const topicsById = new Map(CROP_TOPICS.map(topic => [topic.id, topic]));
const topicsByCommodity = new Map();
for (const topic of CROP_TOPICS) {
  for (const id of topic.commodityIds) {
    if (topicsByCommodity.has(id)) throw new Error(`Duplicate editorial commodity mapping: ${id}`);
    topicsByCommodity.set(id, topic);
  }
}

/** Topic IDs only; useful when validating CMS metadata. */
// Processed or milled forms share a topic for browsing, but the topic's guides are about
// growing and handling the crop; these pages do not list them as if they applied.
export const PROCESSED_FORM_IDS = Object.freeze(new Set([
  'wheat-atta', 'rice', 'basmati-rice', 'broken-rice', 'beaten-rice', 'mustard-oil', 'ground-nut-oil',
  'bengal-gram-dalchana-dal', 'arhar-daltur-dal', 'red-gram-split-arhar-dal-tur-dal', 'green-gram-dalmoong-dal',
  'black-gram-dalurd-dal', 'masur-dal',
]));
export const isProcessedForm = id => PROCESSED_FORM_IDS.has(String(id || '').trim().toLowerCase());

export function getTopicById(id) {
  return topicsById.get(normalizeId(id)) ?? null;
}

/** Exact commodity ID or editorial topic ID; never infer from partial names. */
export function getCropTopic(id) {
  const key = normalizeId(id);
  return topicsByCommodity.get(key) ?? topicsById.get(key) ?? null;
}
